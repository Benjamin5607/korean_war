let currentLang = localStorage.getItem("kw_lang") || "ko";

export function setLang(lang) {
  currentLang = lang === "en" ? "en" : "ko";
  localStorage.setItem("kw_lang", currentLang);
}

export function getLang() {
  return currentLang;
}

export function t(key, ...args) {
  const s = STRINGS[currentLang][key] ?? STRINGS.ko[key] ?? key;
  return args.reduce((acc, val, i) => acc.replace(`{${i}}`, val), s);
}

export function tScenario(id, field) {
  const data = SCENARIO_TEXT[currentLang]?.[id];
  return data?.[field] ?? SCENARIO_TEXT.ko[id]?.[field] ?? "";
}

export const SCENARIO_TEXT = {
  ko: {},
  en: {},
};

export function registerScenarioText(id, ko, en) {
  SCENARIO_TEXT.ko[id] = ko;
  SCENARIO_TEXT.en[id] = en;
}

